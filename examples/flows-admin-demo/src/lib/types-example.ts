/**
 * Example: Helper to create typed journey from form data
 */
export function createOnboardingJourney(formData: {
	title: string;
	employee_email: string;
	department: string;
	start_date: string;
	location: string;
	manager_id: string;
}): FlowsEntityCreate<OnboardingJourney> {
	return {
		client_id: 'demo',
		app_id: 'flows',
		title: formData.title,
		description: `Onboarding for ${formData.employee_email}`,
		status: 'invited',
		invited_at: new Date(),
		owner_id: formData.manager_id,
		participants: [formData.employee_email, formData.manager_id],
		primary_participant_id: formData.employee_email,
		metadata: {
			department: formData.department,
			start_date: formData.start_date,
			location: formData.location,
			manager_id: formData.manager_id
		}
	};
}
