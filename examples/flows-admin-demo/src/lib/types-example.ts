/**
 * Example showing how to use @thepia/flows-db types in the admin demo
 *
 * This file demonstrates importing and using the type-safe Flows data types
 * from the workspace package.
 */

import type {
	FlowsJourney,
	FlowsTask,
	FlowsAttachment,
	FlowsEvidence,
	FlowsEntityCreate,
	FlowsEntityUpdate,
	FlowsDBProcedures,
	ProcedureInput,
	ProcedureOutput
} from '@thepia/flows-db/types';

/**
 * Example: Create a new journey with full type safety
 */
export function createExampleJourney(): FlowsEntityCreate<FlowsJourney> {
	return {
		client_id: 'demo',
		app_id: 'flows',
		title: 'Employee Onboarding',
		description: 'Complete all onboarding tasks',
		status: 'invited',
		invited_at: new Date(),
		owner_id: 'manager-123',
		participants: ['employee-456'],
		metadata: {
			department: 'Engineering',
			start_date: '2025-11-01'
		}
		// Note: id, created_at, updated_at are excluded (generated by system)
	};
}

/**
 * Example: Update a journey with partial data
 */
export function createJourneyUpdate(): FlowsEntityUpdate<FlowsJourney> {
	return {
		status: 'active',
		started_at: new Date(),
		progress_percentage: 25
		// All fields are optional in updates
	};
}

/**
 * Example: Type-safe query input
 */
export function createTaskQuery(journeyId: string): ProcedureInput<'query.tasks'> {
	return {
		filter: {
			eq: { journey_id: journeyId, status: 'pending' }
		},
		orderBy: [{ column: 'order', ascending: true }],
		limit: 10
	};
}

