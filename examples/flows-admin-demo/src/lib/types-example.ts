/**
 * Example: Type guards for runtime checks
 */
export function isJourney(entity: unknown): entity is FlowsJourney {
	return (
		typeof entity === 'object' &&
		entity !== null &&
		'title' in entity &&
		'status' in entity &&
		'invited_at' in entity &&
		['invited', 'active', 'completed', 'cancelled', 'archived'].includes(
			(entity as FlowsJourney).status
		)
	);
}

export function isTask(entity: unknown): entity is FlowsTask {
	return (
		typeof entity === 'object' &&
		entity !== null &&
		'journey_id' in entity &&
		'title' in entity &&
		'status' in entity &&
		['pending', 'in_progress', 'completed', 'cancelled', 'blocked'].includes(
			(entity as FlowsTask).status
		)
	);
}

